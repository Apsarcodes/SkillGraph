class VectorRAGStore:
    def __init__(self):
        self.chunks: List[Dict] = []
        self.vocabulary: Dict[str, int] = {}
        self.idf: Dict[str, float] = {}
        self._initialize_knowledge_base()

    def _tokenize(self, text: str) -> List[str]:
        cleaned = re.sub(r'[^a-zA-Z0-9\s]', ' ', text.lower())
        return [w for w in cleaned.split() if len(w) > 2]

    def _initialize_knowledge_base(self):
        """Chunks documents and indexes them for vector cosine retrieval."""
        all_chunks = []
        doc_count = len(CURATED_KNOWLEDGE_BASE)
        df_counts = Counter()

        for doc in CURATED_KNOWLEDGE_BASE:
            text = doc["content"]
            # Split into ~2 sentence semantic chunks
            sentences = [s.strip() for s in text.split('. ') if len(s.strip()) > 10]
            for i in range(len(sentences)):
                chunk_text = ". ".join(sentences[i:i+2])
                tokens = self._tokenize(chunk_text)
                unique_tokens = set(tokens)
                for tok in unique_tokens:
                    df_counts[tok] += 1
                
                all_chunks.append({
                    "id": f"{doc['id']}_chk_{i}",
                    "documentId": doc["id"],
                    "title": doc["title"],
                    "source": doc["source"],
                    "chapter": doc["chapter"],
                    "text": chunk_text,
                    "tokens": tokens,
                    "term_counts": Counter(tokens),
                    "length": len(tokens)
                })

        # Compute IDF
        N = max(len(all_chunks), 1)
        for term, df in df_counts.items():
            self.idf[term] = math.log((N + 1) / (df + 1)) + 1.0

        # Compute chunk vector norms
        for chk in all_chunks:
            tf_idf_sq_sum = 0.0
            for term, count in chk["term_counts"].items():
                tf = count / max(chk["length"], 1)
                weight = tf * self.idf.get(term, 1.0)
                tf_idf_sq_sum += weight ** 2
            chk["norm"] = math.sqrt(tf_idf_sq_sum) or 1.0

        self.chunks = all_chunks

    def search(self, query: str, top_k: int = 2) -> List[Dict]:
        """
        Executes cosine similarity search over vector chunks and returns ranked citations.
        """
        query_tokens = self._tokenize(query)
        if not query_tokens:
            return []

        query_counts = Counter(query_tokens)
        q_sq_sum = 0.0
        q_weights = {}
        for term, count in query_counts.items():
            tf = count / len(query_tokens)
            weight = tf * self.idf.get(term, 1.0)
            q_weights[term] = weight
            q_sq_sum += weight ** 2
        q_norm = math.sqrt(q_sq_sum) or 1.0

        results = []
        for chk in self.chunks:
            dot_product = 0.0
            for term, q_w in q_weights.items():
                if term in chk["term_counts"]:
                    c_tf = chk["term_counts"][term] / max(chk["length"], 1)
                    c_w = c_tf * self.idf.get(term, 1.0)
                    dot_product += q_w * c_w

            similarity = dot_product / (q_norm * chk["norm"])
            if similarity > 0.05:
                results.append((similarity, chk))

        results.sort(key=lambda x: x[0], reverse=True)
        top_results = results[:top_k]

        citations = []
        for sim, chk in top_results:
            citations.append({
                "documentId": chk["documentId"],
                "title": chk["title"],
                "source": chk["source"],
                "chapter": chk["chapter"],
                "relevanceScore": round(float(sim), 3),
                "excerpt": chk["text"]
            })
        return citations

    def generate_grounded_response(self, query: str) -> Dict:
        """
        Retrieves relevant context and synthesizes a grounded answer with citations.
        """
        citations = self.search(query, top_k=2)

        if not citations:
            return {
                "text": (
                    "I searched the engineering curriculum knowledge base for your query. "
                    "While there is no exact high-confidence chapter match, general engineering principles recommend "
                    "mastering prerequisite data structures and foundational containerization before proceeding to advanced topics."
                ),
                "citations": [],
                "isFallback": True
            }

        # Synthesize grounded answer
        excerpts_text = " ".join([c["excerpt"] for c in citations])
        main_title = citations[0]["title"]
        main_chapter = citations[0]["chapter"]

        grounded_answer = (
            f"Based on verified curriculum documentation from {main_title} ({main_chapter}):\n\n"
            f"{citations[0]['excerpt']}\n\n"
            f"Key Takeaway: To apply this effectively in your roadmap, focus on aligning system design "
            f"trade-offs with your current skill gaps."
        )

        return {
            "text": grounded_answer,
            "citations": citations,
            "isFallback": True
        }

